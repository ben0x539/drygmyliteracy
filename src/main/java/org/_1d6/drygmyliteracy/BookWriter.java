    // strings, so, uh, let's just leave existing pages completely untouched
    // and track a new, in-progress page using regular strings and then
    // send that into a passthrough filterable?
    //
    // We maintain the invariant of pages having 100 or fewer elements, and
    // additionally keep newPage null if it is at 100 elements. newPage of
    // course has to be under 14 elements.
    private static final int PAGES_PER_BOOK = 100;
    private static final int LINES_PER_PAGE = 14;
    private static final int PIXELS_PER_LINE = 114;

    private final List<Filterable<String>> pages;
    private List<String> newPage;

    public BookWriter(ItemStack book) {
        WritableBookContent content = book.get(DataComponents.WRITABLE_BOOK_CONTENT);
        if (content != null) {
            pages = new ArrayList<>(content.pages());
        } else {
            pages = new ArrayList<>();
        }
        newPage = null;
    }

    private boolean maybePrepareNewPage() {
        if (pages.size() >= PAGES_PER_BOOK) {
            return false;
        }

        if (newPage != null && !newPage.isEmpty()) {
            pages.add(Filterable.passThrough(String.join("\n", newPage)));
        }

        newPage = new ArrayList<>();
        return true;
    }

    public boolean writeLine(@NotNull String line) {
        var lines = wrapLines(line);
        for (var s : lines) {
            if (newPage == null || newPage.size() >= LINES_PER_PAGE) {
                if (!maybePrepareNewPage())
                    return false;
            }

            newPage.add(s);
        }

        return true;
    }

    public void update(ItemStack book) {
        maybePrepareNewPage();
        // todo do we need to stop mutating pages after this? like it won't come up but
        book.set(DataComponents.WRITABLE_BOOK_CONTENT, new WritableBookContent(pages));
    }

    static List<String> wrapLines(@NotNull String s) {
        var lines = new ArrayList<String>();
        while (!s.isEmpty()) {
            int j = getWrapPoint(s);
            String prefix = s.substring(0, j);
            if (s.startsWith(" ", j)) {
                ++j;
            }
            s = s.substring(j);

            lines.add(prefix);
        }
        return lines;
    }

    static int getWrapPoint(@NotNull String line) {
        int lineWidth = 0;
        int i = 0;

        while (i < line.length()) {
            int w = getPixelWidth(line.codePointAt(i)) + 1;
            if (lineWidth + w > PIXELS_PER_LINE) {
                break;
            }

            lineWidth += w;
            i = line.offsetByCodePoints(i, 1);
        }

        if (i != line.length()) {
            int j = line.lastIndexOf(' ', i);
            if (j != -1) {
                return j;
            }
        }
        return i;
    }

